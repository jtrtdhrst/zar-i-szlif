for (const name of FORBIDDEN_MUTATING_TOOLS) {
  if (READ_ONLY_TOOLS.has(name)) {
    throw new Error(`read-only allowlist must not contain mutating tool: ${name}`);
  }
}

export function isReadOnlyTool(name) {
  return READ_ONLY_TOOLS.has(String(name));
}
